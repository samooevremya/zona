window.inhabitedWorldCheck=()=>{
  const checked=[];
  const ok=(value,label)=>{if(!value)throw Error(label);checked.push(label);};
  ok(atpAge()===-1&&!nightLamps().has(HOUSES.find(h=>h.ok===atpRooms[0])),'unoccupied garage dark');
  const bunkerPos=locPt('atp','garage');
  P.x=bunkerPos.x;P.y=bunkerPos.y;
  occupyATP();
  ok(atpAge()===0&&!nightLamps().has(HOUSES.find(h=>h.ok===atpRooms[0])),'first hours');
  S.min+=100;
  ok(atpAge()>=90&&nightLamps().has(HOUSES.find(h=>h.ok===atpRooms[0])),'garage lamp after setup');
  S.min+=630;
  save(true);applyState(loadSave());
  ok(atpAge()>=720,'occupation survives load');
  const sentry=atpCompany().find(n=>n.alive&&!n.wounded&&!n.follow);
  sentry.trip=null;sentry.tgt=null;sentry.mem=0;S.blow={stage:0,next:S.min+200};
  ok(atpNewSentry(sentry),'sentry chosen');
  const {guardPoint}=atpScene();
  ok(clearWalk(guardPoint.x,guardPoint.y,guardPoint.x,guardPoint.y,sentry.r),'sentry at accessible point');
  const house=HOUSES.find(h=>h.ok==='15,72'),outerY=(house.y+house.h)*T;
  P.x=(house.x+3.5)*T;P.y=outerY+50;cam.x=P.x;cam.y=P.y;S.min=1370;
  render();
  const pane=house.litPanes.find(p=>p.ny===1);
  ok(!!pane,'lit pane on visible wall');
  Object.assign(sentry,{x:pane.wallX,y:pane.wallY-22,sit:0});
  ok(windowOcclusion(pane.wallX,pane.wallY,0,1),'person casts passing silhouette');
  const bar=HOUSES.find(h=>h.ok==='78,118'),door=bar.entrances[0];
  const x=bar.x*T+door.x,y=bar.y*T+door.y;
  surfaceWater=.8;
  Object.assign(P,{x,y:y-48});leaveBootMark(P);
  Object.assign(P,{x,y:y+33});leaveBootMark(P,{x:P.x,y:P.y,a:Math.PI/2});
  ok(bootMarks.some(m=>m.wet>.5&&m.x===P.x),'wet steps from yard to bar');
  const lookout=HOUSES.find(h=>h.x===WEST+15&&h.y===NORTH_ROWS+28);
  ok(lookout.entrances.some(d=>d.approach==='porch')&&lookout.porchDepth>0,'raised lookout threshold');
  return checked;
};
